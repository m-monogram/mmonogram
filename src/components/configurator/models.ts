/**
 * Отсев обломков прореживания. Меш из пары треугольников, растянутый при этом
 * на метры, — это схлопнутая деталь: вершин не осталось, а габарит от исходной
 * геометрии сохранился. В сцене такой обломок выглядит огромным плоским
 * лоскутом поперёк машины.
 *
 * Мерим средний из трёх размеров, а не наименьший: обломок обычно плоский,
 * то есть велик по двум осям и нулевой по третьей. Настоящие тонкие детали —
 * молдинги, полоса фонаря — велики только вдоль одной оси, и средний размер
 * у них крошечный.
 */
