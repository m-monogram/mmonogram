--
-- Читать bookings ему и так нечего: единственная политика на чтение
-- (Admin/editor read bookings) выдана роли authenticated и требует
-- is_admin_or_editor, поэтому RLS возвращает анониму пустой набор.
-- Но пока держится сам GRANT, вся защита базы лидов висит на одной
-- политике: снимут RLS при отладке или добавят пермиссивную политику —
-- и телефоны с почтами клиентов уедут одним GET-запросом.
--
-- Публичному сайту чтение не нужно: форма делает insert() без select()
-- (см. src/lib/leads.ts), заявки читает только админка под авторизацией.
